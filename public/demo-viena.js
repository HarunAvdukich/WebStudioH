// Minute od ponoći dana polaska sa prve stanice; prelaz preko ponoći se dodaje na 24 h.
function vremenaPolaska(linija, k) {
  const out = []
  let pret = -1, dodaj = 0
  for (const red of linija.stanice) {
    const v = red[1 + k] ?? red[1]
    let m
    if (v.startsWith('+')) m = pret + Number(v.slice(1))
    else {
      const [h, mi] = v.split(':').map(Number)
      m = h * 60 + mi + dodaj
      if (m < pret) { dodaj += 1440; m += 1440 }
    }
    out.push({ ime: red[0], m, okvirno: v.startsWith('+') })
    pret = m
  }
  return out
}

function cijena(od, doo) {
  const van = strana(od) === 'van' ? od : doo
  return CIJENE[van] ?? 60
}

// Svi polasci sa stanice "od" do "doo" kojima je polazak sa stanice "od" na dati dan.
function nadjiPolaske(od, doo, dan) {
  const out = []
  for (const l of LINIJE) {
    l.polasci.forEach((p, k) => {
      const v = vremenaPolaska(l, k)
      const i = v.findIndex((s) => s.ime === od)
      const j = v.findIndex((s) => s.ime === doo)
      if (i < 0 || j < 0 || i >= j) return
      const pomak = Math.floor(v[i].m / 1440)
      const start = plusDana(dan, -pomak)
      if (!p.dani(start).includes(start.getDay())) return
      out.push({
        id: `${l.id}-${k}-${iso(start)}`, linija: l, polazak: p, k, start, dan,
        od, doo, kreni: v[i].m, stigni: v[j].m, okvirno: v[j].okvirno, put: v, i, j,
        cijena: cijena(od, doo),
      })
    })
  }
  return out.sort((a, b) => (a.kreni % 1440) - (b.kreni % 1440))
}

